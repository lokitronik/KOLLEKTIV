export function getFreshDemoReports(): Report[] {
  const now = Date.now();
  const offsets = [
    { minsAgo: 2, expiryMins: 118 },
    { minsAgo: 5, expiryMins: 25 },
    { minsAgo: 9, expiryMins: 171 },
    { minsAgo: 14, expiryMins: 31 },
    { minsAgo: 24, expiryMins: 336 },
    { minsAgo: 18, expiryMins: 27 },
    { minsAgo: 22, expiryMins: 23 }
  ];

  return INITIAL_DEMO_REPORTS.map((rep, idx) => {
    const offset = offsets[idx % offsets.length];
    const createdAt = new Date(now - offset.minsAgo * 60 * 1000).toISOString();
    const expiresAt = new Date(now + offset.expiryMins * 60 * 1000).toISOString();
    return {
      ...rep,
      createdAt,
      updatedAt: createdAt,
      expiresAt,
      status: 'aktiv' as const
    };
  });
}
